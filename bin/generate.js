/**
 * Scans src/ for "// METHOD /path" comments and writes setup.js
 * with plain static imports, so the app bundles normally.
 * Runs on Node and Bun.
 */

import fs from "node:fs";
import path from "node:path";

const ROUTE_REGEX = /^\/\/\s*(GET|POST|PUT|PATCH|DELETE)\s+(\S+)\s*$/gm;
const HEADER = "// Auto generated by maxserver, do not edit";


/**
 * All .js files, sorted, without node_modules, dotfiles and tests.
 */
function walk(dir, out = []) {
	if (!fs.existsSync(dir)) return out;

	const entries = fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name));
	for (const e of entries) {
		if (e.name === "node_modules" || e.name.startsWith(".")) continue;

		const full = path.join(dir, e.name);
		if (e.isDirectory()) walk(full, out);
		else if (e.name.endsWith(".js") && !e.name.endsWith(".test.js")) out.push(full);
	}
	return out;
}


function hasDefaultExport(text) {
	return /^\s*export\s+default\b/m.test(text);
}


/**
 * Collects routes and models. Throws clear errors with file paths.
 */
export function collect(root, dir = "src") {
	const rel = f => path.relative(root, f).split(path.sep).join("/");
	const files = walk(path.resolve(root, dir));
	const routes = [];
	const models = [];
	const seen = new Map();

	for (const file of files) {
		const text = fs.readFileSync(file, "utf8");

		// 1. Models: .schema.js without sibling .js
		if (file.endsWith(".schema.js")) {
			if (fs.existsSync(file.replace(/\.schema\.js$/, ".js"))) continue;
			if (!hasDefaultExport(text)) throw new Error(`${rel(file)}: model schema must use export default`);
			models.push({ file: rel(file) });
			continue;
		}

		// 2. Routes: exactly one magic comment
		const matches = [...text.matchAll(ROUTE_REGEX)];
		if (matches.length === 0) continue;
		if (matches.length > 1) throw new Error(`${rel(file)}: only one route comment allowed per file, found ${matches.length}`);
		if (!hasDefaultExport(text)) throw new Error(`${rel(file)}: route must export a default handler function`);

		const method = matches[0][1];
		const url = "/" + matches[0][2].replace(/^\/+/, "");

		// 3. Duplicates
		const key = `${method} ${url}`;
		if (seen.has(key)) throw new Error(`Duplicate route "${key}" in ${seen.get(key)} and ${rel(file)}`);
		seen.set(key, rel(file));

		const schemaFile = file.replace(/\.js$/, ".schema.js");
		const schema = fs.existsSync(schemaFile) ? rel(schemaFile) : null;
		if (schema && !hasDefaultExport(fs.readFileSync(schemaFile, "utf8")))
			throw new Error(`${schema}: schema must use export default`);

		routes.push({ method, path: url, file: rel(file), schema });
	}

	return { routes, models };
}


const str = JSON.stringify;


/**
 * setup.js source code.
 */
export function render({ routes, models }) {
	const imports = [];
	const modelList = [];
	const routeList = [];

	models.forEach((m, i) => {
		imports.push(`import m${i} from ${str("./" + m.file)};`);
		modelList.push(`\t\t{ file: ${str(m.file)}, schema: m${i} },`);
	});

	routes.forEach((r, i) => {
		imports.push(`import h${i} from ${str("./" + r.file)};`);
		if (r.schema) imports.push(`import s${i} from ${str("./" + r.schema)};`);
		const schema = r.schema ? `, schema: s${i}` : "";
		routeList.push(`\t\t{ method: "${r.method}", path: ${str(r.path)}, file: ${str(r.file)}, handler: h${i}${schema} },`);
	});

	return [
		HEADER,
		`import { register } from "maxserver";`,
		...imports,
		"",
		"register({",
		"\tmodels: [",
		...modelList,
		"\t],",
		"\troutes: [",
		...routeList,
		"\t],",
		"});",
		"",
		"// server.js last: static imports above run first, so routes are registered before it starts",
		`await import("./server.js");`,
		"",
	].join("\n");
}


/**
 * Writes setup.js in root, only if content changed. Returns the collected routes.
 */
export function generate(root = process.cwd(), dir = process.env.ROUTESDIR || "src") {
	if (!fs.existsSync(path.join(root, "server.js")))
		throw new Error(`server.js not found in ${root}`);

	const result = collect(root, dir);
	const code = render(result);
	const out = path.join(root, "setup.js");

	const old = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : null;
	if (old !== code) fs.writeFileSync(out, code);
	return result;
}
