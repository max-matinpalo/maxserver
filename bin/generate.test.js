import { test, expect, beforeEach, afterEach } from "bun:test";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { collect, generate } from "./generate.js";

let root;

function write(file, text) {
	const full = path.join(root, file);
	fs.mkdirSync(path.dirname(full), { recursive: true });
	fs.writeFileSync(full, text);
}

const route = (method, url) => `// ${method} ${url}\n\nexport default async function (req, res) {}\n`;

beforeEach(() => {
	root = fs.mkdtempSync(path.join(os.tmpdir(), "maxserver-gen-"));
	write("server.js", "");
});

afterEach(() => fs.rmSync(root, { recursive: true, force: true }));


test("finds magic comments in nested folders with params", () => {
	write("src/a/b/c/deep.js", route("PATCH", "/forms/:formId/questions/:questionId"));
	write("src/hello.js", route("GET", "hello"));

	expect(collect(root).routes).toEqual([
		{ method: "PATCH", path: "/forms/:formId/questions/:questionId", file: "src/a/b/c/deep.js", schema: null },
		{ method: "GET", path: "/hello", file: "src/hello.js", schema: null },
	]);
});

test("ignores files without comment, tests, dotfolders and node_modules", () => {
	write("src/util.js", "export function x() {}\n");
	write("src/x.test.js", route("GET", "/t"));
	write("src/.hidden/h.js", route("GET", "/h"));
	write("src/node_modules/n.js", route("GET", "/n"));

	expect(collect(root).routes).toEqual([]);
});

test("sibling .schema.js belongs to the route", () => {
	write("src/hello.js", route("POST", "/hello"));
	write("src/hello.schema.js", "export default {};\n");

	expect(collect(root).routes[0].schema).toBe("src/hello.schema.js");
});

test("schema without sibling .js is a model", () => {
	write("src/Models/User.schema.js", "export default { $id: 'User' };\n");
	expect(collect(root).models).toEqual([{ file: "src/Models/User.schema.js" }]);
});

test("setup.js: top comment, static imports, register, server.js last", () => {
	write("src/hello.js", route("POST", "/hello"));
	write("src/hello.schema.js", "export default {};\n");
	write("src/Models/User.schema.js", "export default { $id: 'User' };\n");
	generate(root);

	const code = fs.readFileSync(path.join(root, "setup.js"), "utf8");
	const lines = code.trim().split("\n");
	expect(lines[0]).toBe("// Auto generated by maxserver, do not edit");
	expect(code).toContain('import { register } from "maxserver";');
	expect(code).toContain('import h0 from "./src/hello.js";');
	expect(code).toContain('import s0 from "./src/hello.schema.js";');
	expect(code).toContain('{ file: "src/Models/User.schema.js", schema: m0 }');
	expect(code).toContain('{ method: "POST", path: "/hello", file: "src/hello.js", handler: h0, schema: s0 }');
	expect(code).not.toContain("import(`");
	expect(lines.at(-1)).toBe('await import("./server.js");');
});

test("setup.js is not rewritten when nothing changed", () => {
	write("src/hello.js", route("GET", "/hello"));
	generate(root);
	const file = path.join(root, "setup.js");
	const before = fs.statSync(file).mtimeMs;
	Bun.sleepSync(20);
	generate(root);
	expect(fs.statSync(file).mtimeMs).toBe(before);
});

test("error: two comments in one file", () => {
	write("src/two.js", "// GET /a\n// POST /b\nexport default () => {};\n");
	expect(() => collect(root)).toThrow("src/two.js: only one route comment allowed per file, found 2");
});

test("error: duplicate route", () => {
	write("src/a.js", route("GET", "/x"));
	write("src/b.js", route("GET", "/x"));
	expect(() => collect(root)).toThrow('Duplicate route "GET /x" in src/a.js and src/b.js');
});

test("error: missing default export", () => {
	write("src/a.js", "// GET /a\nexport function handler() {}\n");
	expect(() => collect(root)).toThrow("src/a.js: route must export a default handler function");
});

test("error: model without export default", () => {
	write("src/Models/User.schema.js", "export const User = {};\n");
	expect(() => collect(root)).toThrow("src/Models/User.schema.js: model schema must use export default");
});

test("error: missing server.js", () => {
	fs.rmSync(path.join(root, "server.js"));
	expect(() => generate(root)).toThrow("server.js not found");
});

test("ROUTESDIR: other routes directory", () => {
	write("api/hello.js", route("GET", "/hello"));
	expect(collect(root, "api").routes[0].file).toBe("api/hello.js");
});
